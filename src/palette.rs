//! `rexroster lua`: the Lua snippet that adds rexroster's actions to Rex's
//! command palette, and `rexroster lua --loader`, the init.lua loader that
//! fetches it from the installed binary when Rex loads its config.

use std::ffi::OsStr;
use std::path::{Path, PathBuf};

const SCRIPT: &str = include_str!("../lua/palette.lua");

/// The snippet: a line that sets `REXROSTER` to `exe`, so the actions run
/// this binary, then the built-in script. Without a usable path the line is
/// left out and the actions find rexroster on `PATH`.
pub fn script(exe: Option<&Path>) -> String {
    match exe.and_then(Path::to_str) {
        Some(exe) => format!("local REXROSTER = {}\n{SCRIPT}", lua_string(exe)),
        None => SCRIPT.to_owned(),
    }
}

/// The first executable file named `rexroster` in the absolute directories of
/// `path` (a `PATH` value), as `PATH` spelled it. Symlinks are not resolved, so a
/// version manager's shim stays the shim and survives upgrades.
pub fn find_on_path(path: Option<&OsStr>) -> Option<PathBuf> {
    std::env::split_paths(path?)
        // A relative or empty entry would mean Rex's directory, not ours.
        .filter(|dir| dir.is_absolute())
        .map(|dir| dir.join("rexroster"))
        .find(|p| is_executable(p))
}

fn is_executable(p: &Path) -> bool {
    use std::os::unix::fs::PermissionsExt;
    p.metadata()
        .is_ok_and(|m| m.is_file() && m.permissions().mode() & 0o111 != 0)
}

/// A Lua loader for Rex's init.lua. At config load it runs `exe lua` and runs
/// the output, so the actions follow the installed binary. Whatever goes
/// wrong (no binary, a failing exit, output that doesn't compile or run) is
/// logged as a warning and never raised, so a bad rexroster can't break the
/// config.
pub fn loader(exe: &str) -> String {
    format!(
        r#"-- rexroster: palette actions, generated by the installed binary
do
  local r, err = rex.exec({{ {exe}, "lua" }}, {{ timeout = 5 }})
  local why
  if not r then
    why = err or "did not run"
  elseif not r.ok then
    why = (r.stderr and r.stderr ~= "") and r.stderr or ("exit " .. tostring(r.code))
  else
    local chunk, cerr = loadstring(r.stdout, "=rexroster lua")
    if chunk then
      local ok, rerr = pcall(chunk)
      if not ok then why = rerr end
    else
      why = cerr
    end
  end
  if why then rex.log("warn", "rexroster: palette actions not loaded: " .. tostring(why)) end
end
"#,
        exe = lua_string(exe)
    )
}

/// `s` as a Lua 5.1 string literal. Quotes, backslashes and control
/// characters are escaped; other bytes are fine as they are.
fn lua_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            c if c.is_ascii_control() => out.push_str(&format!("\\{:03}", c as u8)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
